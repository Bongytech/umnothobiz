#!/usr/bin/env node
/**
 * Creates .env.local from the public Firebase web config served by the live
 * hosting site. This is a convenience for contributors; the values are
 * identifiers, not server secrets.
 *
 * Usage:
 *   npm run setup:env
 *   npm run setup:env -- --force
 *   FIREBASE_CONFIG_URL=http://localhost:5000/__/firebase/init.json npm run setup:env
 */

import { existsSync, writeFileSync } from 'node:fs';

const CONFIG_URL =
  process.env.FIREBASE_CONFIG_URL ?? 'https://umnothobiz.web.app/__/firebase/init.json';
const TARGET = '.env.local';
const force = process.argv.includes('--force');
const dryRun = process.argv.includes('--dry-run');
const emulator = process.argv.includes('--emulator');

const required = [
  ['apiKey', 'VITE_FIREBASE_API_KEY'],
  ['authDomain', 'VITE_FIREBASE_AUTH_DOMAIN'],
  ['projectId', 'VITE_FIREBASE_PROJECT_ID'],
  ['storageBucket', 'VITE_FIREBASE_STORAGE_BUCKET'],
  ['messagingSenderId', 'VITE_FIREBASE_MESSAGING_SENDER_ID'],
  ['appId', 'VITE_FIREBASE_APP_ID'],
];

if (existsSync(TARGET) && !force && !dryRun) {
  console.log(`${TARGET} already exists. Re-run with "-- --force" to overwrite it.`);
  process.exit(0);
}

if (emulator) {
  const lines = [
    '# Generated by npm run setup:env -- --emulator. Safe for local testing only.',
    'VITE_FIREBASE_API_KEY=demo-api-key',
    'VITE_FIREBASE_AUTH_DOMAIN=demo-umnotho.firebaseapp.com',
    'VITE_FIREBASE_PROJECT_ID=demo-umnotho',
    'VITE_FIREBASE_STORAGE_BUCKET=demo-umnotho.appspot.com',
    'VITE_FIREBASE_MESSAGING_SENDER_ID=000000000000',
    'VITE_FIREBASE_APP_ID=1:000000000000:web:demo',
    'VITE_FIREBASE_MEASUREMENT_ID=G-DEMO',
    'VITE_USE_FIREBASE_EMULATORS=true',
  ];

  if (dryRun) {
    console.log(`Would write ${TARGET} for the Firebase emulators.`);
    process.exit(0);
  }

  writeFileSync(TARGET, `${lines.join('\n')}\n`, 'utf8');
  console.log(`Wrote ${TARGET} for the Firebase emulators.`);
  console.log('Start the emulators with: npm run emulators');
  console.log('Then start the app with: npm run dev');
  process.exit(0);
}

console.log(`Fetching Firebase web config from ${CONFIG_URL} ...`);
const response = await fetch(CONFIG_URL);

if (!response.ok) {
  throw new Error(`Could not fetch the Firebase config (HTTP ${response.status}).`);
}

const config = await response.json();
const missing = required.filter(([key]) => !config[key]);

if (missing.length > 0) {
  throw new Error(
    `The Firebase config is incomplete. Missing: ${missing.map(([key]) => key).join(', ')}.`,
  );
}

const lines = [
  '# Generated by npm run setup:env. Values are public Firebase web identifiers.',
  ...required.map(([key, envKey]) => `${envKey}=${config[key]}`),
  config.measurementId ? `VITE_FIREBASE_MEASUREMENT_ID=${config.measurementId}` : null,
  'VITE_USE_FIREBASE_EMULATORS=false',
].filter(Boolean);

if (dryRun) {
  console.log(`Would write ${TARGET} with ${lines.length - 2} Firebase values.`);
  process.exit(0);
}

writeFileSync(TARGET, `${lines.join('\n')}\n`, 'utf8');
console.log(`Wrote ${TARGET}. Restart the dev server with: npm run dev`);
